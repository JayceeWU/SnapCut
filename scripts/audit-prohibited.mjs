import { readFile, readdir } from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const textExtensions = new Set(['.js', '.mjs', '.cjs', '.ts', '.tsx', '.kt', '.kts', '.java']);
const ignoredDirectories = new Set([
  '.git',
  '.expo',
  '.agents',
  'ios',
  'node_modules',
  'coverage',
  'copypaste',
  'build',
  '.cxx',
  'third_party',
]);

const forbiddenDependencies = [
  'expo-audio',
  'expo-av',
  'ffmpeg-kit-react-native',
  'react-native-ffmpeg',
  'react-native-video-trim',
  'lamejs',
];

const forbiddenSourcePatterns = [
  { label: 'FFmpeg', pattern: /ffmpeg(?:kit)?/iu },
  {
    label: 'Base64 media transfer',
    pattern: /(?:readAsStringAsync|EncodingType)\s*\.?(?:Base64|base64)/u,
  },
  {
    label: 'JavaScript media byte access',
    pattern: /(?:arrayBuffer|FileReader|readAsStringAsync)\s*\(/u,
  },
  { label: 'network media input', pattern: /https?:\/\//u },
];

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    if (entry.isDirectory() && ignoredDirectories.has(entry.name)) continue;
    const absolutePath = path.join(directory, entry.name);
    // The root Android project is generated by Expo prebuild. The local
    // module's Android sources are product code and must remain in the audit.
    if (entry.isDirectory() && entry.name === 'android' && directory === root) continue;
    if (entry.isDirectory()) files.push(...(await walk(absolutePath)));
    else if (textExtensions.has(path.extname(entry.name))) files.push(absolutePath);
  }
  return files;
}

const packageJson = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const installedNames = new Set([
  ...Object.keys(packageJson.dependencies ?? {}),
  ...Object.keys(packageJson.devDependencies ?? {}),
]);
const violations = forbiddenDependencies
  .filter((dependency) => installedNames.has(dependency))
  .map((dependency) => `Forbidden dependency: ${dependency}`);

for (const filePath of await walk(root)) {
  if (filePath.endsWith(path.join('scripts', 'audit-prohibited.mjs'))) continue;
  const source = await readFile(filePath, 'utf8');
  for (const rule of forbiddenSourcePatterns) {
    if (rule.pattern.test(source)) {
      violations.push(`${rule.label}: ${path.relative(root, filePath)}`);
    }
  }
}

const appConfig = await readFile(path.join(root, 'app.config.ts'), 'utf8');
for (const permission of [
  'MANAGE_EXTERNAL_STORAGE',
  'READ_EXTERNAL_STORAGE',
  'WRITE_EXTERNAL_STORAGE',
  'READ_MEDIA_AUDIO',
  'READ_MEDIA_IMAGES',
  'READ_MEDIA_VIDEO',
  'SYSTEM_ALERT_WINDOW',
]) {
  if (!appConfig.includes(`android.permission.${permission}`)) {
    violations.push(`Missing blocked Android permission: ${permission}`);
  }
}

if (violations.length > 0) {
  console.error(violations.join('\n'));
  process.exitCode = 1;
} else {
  console.log('Prohibited implementation audit passed.');
}
